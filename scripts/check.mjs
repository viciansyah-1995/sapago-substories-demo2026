import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const errors=[],badResponses=[],external=[];
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400)badResponses.push([r.status(),r.url()]);});
 await page.route('**/*',route=>{if(!route.request().url().startsWith('http://localhost:4173/')){external.push(route.request().url());route.abort();}else route.continue();});
 await page.goto('http://localhost:4173/',{waitUntil:'networkidle'});await page.evaluate(()=>document.fonts.ready);
 console.log('Checking desktop and local assets');
 assert.equal(await page.title(),'Sapago x Substories Demo');
 assert.equal(await page.locator('.c-section').count(),16);
 await page.screenshot({path:'qa/local-desktop.png'});
 await page.screenshot({path:'qa/local-full-desktop.png',fullPage:true});
 await page.locator('.hl-faq-child-heading').first().click();
 assert.equal(await page.locator('.hl-faq-child-heading').first().getAttribute('aria-expanded'),'true');
 assert(await page.locator('#demo-faq-0').isVisible());
 await page.locator('.hl-faq-child-heading').first().press('Enter');
 assert.equal(await page.locator('.hl-faq-child-heading').first().getAttribute('aria-expanded'),'false');
 console.log('Checking gallery');
 const track=page.locator('.carousel:visible').first().locator('.carousel__slides');
 const before=await track.getAttribute('style');
 await page.locator('.carousel:visible').first().getByRole('button',{name:'Foto berikutnya'}).click();
 assert.notEqual(await track.getAttribute('style'),before);
 console.log('Checking forms');
 await page.locator('#button-0EFuotkRmbS_btn').click();
 assert(await page.getByRole('dialog').isVisible());
 await page.locator('#demo-name').fill('Demo Substories');
 await page.locator('#demo-phone').fill('081234567890');
 await page.locator('#demo-business').fill('Demo Hotel');
 await page.getByRole('button',{name:'Submit',exact:true}).click();
 assert(await page.getByRole('heading',{name:'Terima kasih!'}).isVisible());
 await page.getByRole('button',{name:'Kembali ke website'}).click();
 await page.getByRole('button',{name:'Download Katalog',exact:true}).first().click();
 assert(await page.getByRole('heading',{name:'Download Katalog',exact:true}).isVisible());
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Sapago untuk Substories'}).click();
 assert(await page.getByText('Aktivasi chat menunggu public widget key khusus Substories.').isVisible());
 await page.keyboard.press('Escape');
 // Load all lazy images while outbound network is blocked.
 await page.evaluate(async()=>{for(const image of document.images)image.loading='eager';await Promise.all([...document.images].map(i=>i.decode().catch(()=>{})));});
 const broken=await page.locator('img').evaluateAll(es=>es.filter(e=>!e.naturalWidth).map(e=>e.src));
 assert.deepEqual(broken,[]);
 assert.deepEqual(external,[]);assert.deepEqual(badResponses,[]);assert.deepEqual(errors,[]);
 console.log('Checking mobile');
 await page.setViewportSize({width:390,height:844});await page.goto('http://localhost:4173/',{waitUntil:'networkidle'});
 await page.screenshot({path:'qa/local-mobile.png'});
 await page.screenshot({path:'qa/local-full-mobile.png',fullPage:true});
 assert(await page.locator('.nav-menu-mobile').isVisible());
 await page.locator('.nav-menu-mobile').click();
 assert(await page.locator('.demo-mobile-panel').isVisible());
 await page.locator('.demo-mobile-panel a').first().click();
 assert(!(await page.locator('.demo-mobile-panel').isVisible()));
 const overflow=await page.evaluate(()=>({viewport:innerWidth,content:document.documentElement.scrollWidth}));
 assert(overflow.content<=overflow.viewport+1,JSON.stringify(overflow));
 const report={date:new Date().toISOString(),sections:16,assets:JSON.parse(await fs.readFile('source/asset-manifest.json','utf8')).assets.length,checked:['desktop rendering','mobile rendering','offline assets','no external requests','FAQ mouse and keyboard','image carousel','consultation form and success','catalog popup','Sapago integration placeholder','mobile menu','horizontal overflow'],errors,badResponses,external};
 await fs.writeFile('qa/report.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
}finally{await browser.close();}
